"""Generate a Home Assistant package for every Wyze camera the bridge knows about.

Usage: python generate_camera_package.py http://wyze-api.home.lan/cameras > packages/wyze_cameras.yaml

The package reads the bridge URL from the HA container's WYZE_CAMERAS_URL env var,
so the generated file holds camera MACs and names but no hosts. Re-run it when
cameras are added, removed or renamed.
"""

import json
import re
import sys
import urllib.request
from collections import Counter

RECENT_SECONDS = 300


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def camera_names(cameras: list[dict]) -> dict[str, str]:
    counts = Counter(c["nickname"] for c in cameras)
    return {
        c["mac"]: c["nickname"] if counts[c["nickname"]] == 1 else f"{c['nickname']} {c['mac'][-4:]}"
        for c in cameras
    }


def camera_entities(mac: str, name: str) -> dict[str, list[dict]]:
    cam = f"(state_attr('sensor.wyze_cameras', 'by_mac') or {{}}).get('{mac}')"
    event = f"({cam} or {{}}).get('last_event')"
    uid = f"wyze_cam_{slug(mac)}"
    return {
        "sensor": [
            {
                "name": f"{name} Last Event",
                "unique_id": f"{uid}_last_event",
                "icon": "mdi:cctv",
                "availability": f"{{{{ {cam} is not none }}}}",
                "state": f"{{% set e = {event} %}}"
                "{{ (e.type ~ (': ' ~ e.tags | join(', ') if e.tags else '')) if e else 'none' }}",
                "attributes": {
                    "event_id": f"{{{{ ({event} or {{}}).get('id') }}}}",
                    "time": f"{{{{ ({event} or {{}}).get('time') }}}}",
                    "tags": f"{{{{ ({event} or {{}}).get('tags', []) }}}}",
                },
            },
            {
                "name": f"{name} Last Event Time",
                "unique_id": f"{uid}_last_event_time",
                "device_class": "timestamp",
                "availability": f"{{{{ {event} is not none }}}}",
                "state": f"{{{{ ({event} or {{}}).get('time') }}}}",
            },
        ],
        "binary_sensor": [
            {
                "name": f"{name} Online",
                "unique_id": f"{uid}_online",
                "device_class": "connectivity",
                "availability": f"{{{{ {cam} is not none }}}}",
                "state": f"{{{{ ({cam} or {{}}).get('online', false) }}}}",
                "attributes": {
                    key: f"{{{{ ({cam} or {{}}).get('{key}') }}}}"
                    for key in ("model", "firmware", "ip", "rssi", "ssid", "battery", "mac")
                },
            },
            {
                "name": f"{name} Recent Event",
                "unique_id": f"{uid}_recent_event",
                "device_class": "motion",
                "availability": f"{{{{ {cam} is not none }}}}",
                "state": f"{{% set e = {event} %}}"
                f"{{{{ e is not none and (now() - as_datetime(e.time)).total_seconds() < {RECENT_SECONDS} }}}}",
            },
        ],
        "image": [
            {
                "name": f"{name} Last Event Image",
                "unique_id": f"{uid}_last_event_image",
                "availability": f"{{{{ ({event} or {{}}).get('image_url') is not none }}}}",
                "url": f"{{{{ ({event} or {{}}).get('image_url', '') }}}}",
            }
        ],
    }


def build_package(cameras: list[dict]) -> dict:
    names = camera_names(cameras)
    template: dict[str, list[dict]] = {"sensor": [], "binary_sensor": [], "image": []}
    for cam in sorted(cameras, key=lambda c: names[c["mac"]].lower()):
        for kind, entities in camera_entities(cam["mac"], names[cam["mac"]]).items():
            template[kind].extend(entities)
    return {
        "rest": [
            {
                "resource": "!env_var WYZE_CAMERAS_URL",
                "scan_interval": 60,
                "timeout": 30,
                "sensor": [
                    {
                        "name": "Wyze Cameras",
                        "unique_id": "wyze_cameras",
                        "icon": "mdi:cctv",
                        "value_template": "{{ value_json.cameras | length }}",
                        "json_attributes": ["by_mac"],
                    }
                ],
            }
        ],
        "template": [template],
    }


def to_yaml(package: dict) -> str:
    # JSON is valid YAML; only the !env_var tag needs to be unquoted.
    body = json.dumps(package, indent=2, ensure_ascii=False)
    body = body.replace('"!env_var WYZE_CAMERAS_URL"', "!env_var WYZE_CAMERAS_URL")
    header = (
        "# Wyze cameras: basic details + latest cloud event per camera, via wyze-bridge-api.\n"
        "# GENERATED by home_assistant/generate_camera_package.py; re-run it instead of editing.\n"
        "# WYZE_CAMERAS_URL = the bridge's /cameras URL, from the HA container's environment.\n"
    )
    return header + body + "\n"


def main() -> None:
    with urllib.request.urlopen(sys.argv[1], timeout=60) as response:
        cameras = json.load(response)["cameras"]
    sys.stdout.write(to_yaml(build_package(cameras)))


if __name__ == "__main__":
    main()
